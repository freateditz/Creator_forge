import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;

import '../../core/logging/app_logger.dart';

const kNativeHostName = 'com.creatorforge.native_host';

final _kExtensionIdRe = RegExp(r'^[a-z]{32}$');

/// Metadata about a detected browser installation.
class BrowserInfo {
  final String id;        // 'chrome' | 'edge' | 'brave'
  final String name;      // human-readable name
  final String? execPath; // absolute path to the browser executable

  const BrowserInfo({required this.id, required this.name, this.execPath});

  bool get isInstalled => execPath != null;
}

/// Detailed diagnostics for the native-host registration of one browser.
class NativeHostDiagnostics {
  final String browserId;
  final bool registryKeyPresent;
  final String? registryManifestPath;
  final bool manifestFilePresent;
  final bool manifestNameCorrect;
  final bool manifestTypeCorrect;
  final String? manifestHostExecPath;
  final bool hostExecPresent;
  final List<String> allowedOrigins;
  final String? parseError;

  const NativeHostDiagnostics({
    required this.browserId,
    required this.registryKeyPresent,
    this.registryManifestPath,
    required this.manifestFilePresent,
    required this.manifestNameCorrect,
    required this.manifestTypeCorrect,
    this.manifestHostExecPath,
    required this.hostExecPresent,
    required this.allowedOrigins,
    this.parseError,
  });

  bool get isHealthy =>
      registryKeyPresent &&
      manifestFilePresent &&
      manifestNameCorrect &&
      manifestTypeCorrect &&
      hostExecPresent &&
      allowedOrigins.isNotEmpty;

  bool containsOrigin(String extensionId) =>
      allowedOrigins.contains('chrome-extension://$extensionId/');

  /// Plain-text report for the "Copy Diagnostics" action.
  String toTextReport() => [
    'CreatorForge Native Host Diagnostics',
    '=====================================',
    'Browser:                  $browserId',
    'Registry key present:     $registryKeyPresent',
    'Registry manifest path:   ${registryManifestPath ?? "(not set)"}',
    'Manifest file present:    $manifestFilePresent',
    'Manifest name correct:    $manifestNameCorrect',
    'Manifest type correct:    $manifestTypeCorrect',
    'Host exec path:           ${manifestHostExecPath ?? "(not set)"}',
    'Host exec present:        $hostExecPresent',
    'Allowed origins:          ${allowedOrigins.isEmpty ? "(none)" : allowedOrigins.join(", ")}',
    if (parseError != null) 'Parse error:              $parseError',
  ].join('\n');
}

class RegistrationResult {
  final bool success;
  final String? error;
  final NativeHostDiagnostics? diagnostics;

  const RegistrationResult({
    required this.success,
    this.error,
    this.diagnostics,
  });
}

/// Manages native messaging host registration and browser detection on Windows.
///
/// All public methods return safe empty/error results on non-Windows platforms.
/// No administrator rights are required — everything is written to HKCU and
/// the user's own %APPDATA% directory.
class NativeHostService {
  final _log = AppLogger.get('NativeHostService');

  // ── Browser registry paths (HKLM App Paths) ─────────────────────────────────

  static const _browserAppPaths = {
    'chrome': r'SOFTWARE\Microsoft\Windows\CurrentVersion\App Paths\chrome.exe',
    'edge': r'SOFTWARE\Microsoft\Windows\CurrentVersion\App Paths\msedge.exe',
    'brave': r'SOFTWARE\Microsoft\Windows\CurrentVersion\App Paths\brave.exe',
  };

  static const _browserNmBases = {
    'chrome': r'Software\Google\Chrome\NativeMessagingHosts',
    'edge': r'Software\Microsoft\Edge\NativeMessagingHosts',
    'brave': r'Software\BraveSoftware\Brave-Browser\NativeMessagingHosts',
  };

  static const _browserNames = {
    'chrome': 'Google Chrome',
    'edge': 'Microsoft Edge',
    'brave': 'Brave Browser',
  };

  // ── File-system helpers ──────────────────────────────────────────────────────

  static String get nativeHostDir {
    if (!Platform.isWindows) return '';
    final appData = Platform.environment['APPDATA'] ?? '';
    return p.join(appData, 'CreatorForge', 'NativeHost');
  }

  static String get manifestPath =>
      p.join(nativeHostDir, '$kNativeHostName.json');

  /// Returns the path to the host executable to register in the NM manifest.
  ///
  /// Priority:
  ///   1. `NativeHost\creator_forge_native_host.exe` beside the Flutter exe
  ///      (installed by the Inno Setup installer when the PyInstaller build
  ///       ships with the installer).
  ///   2. `%APPDATA%\CreatorForge\NativeHost\creator_forge_host.bat`
  ///      (generated by install_native_host.ps1 at install time).
  ///
  /// Returns null when neither is found.
  String? findHostExecutable() {
    if (!Platform.isWindows) return null;

    // Production exe — next to creator_forge.exe.
    final appDir = p.dirname(Platform.resolvedExecutable);
    final exePath = p.join(
      appDir,
      'NativeHost',
      'creator_forge_native_host.exe',
    );
    if (File(exePath).existsSync()) return exePath;

    // Fallback — bat wrapper from install_native_host.ps1.
    final batPath = p.join(nativeHostDir, 'creator_forge_host.bat');
    if (File(batPath).existsSync()) return batPath;

    return null;
  }

  // ── Browser detection ────────────────────────────────────────────────────────

  Future<List<BrowserInfo>> detectBrowsers() async {
    if (!Platform.isWindows) return [];

    final results = <BrowserInfo>[];
    for (final entry in _browserAppPaths.entries) {
      final id = entry.key;
      // Check HKLM first; fall back to HKCU.
      var execPath = await _readRegistryDefault('HKLM', entry.value);
      execPath ??= await _readRegistryDefault('HKCU', entry.value);
      results.add(BrowserInfo(
        id: id,
        name: _browserNames[id]!,
        execPath: execPath,
      ));
    }
    return results;
  }

  // ── Diagnostics ──────────────────────────────────────────────────────────────

  Future<NativeHostDiagnostics> diagnose(String browserId) async {
    if (!Platform.isWindows) {
      return NativeHostDiagnostics(
        browserId: browserId,
        registryKeyPresent: false,
        manifestFilePresent: false,
        manifestNameCorrect: false,
        manifestTypeCorrect: false,
        hostExecPresent: false,
        allowedOrigins: const [],
        parseError: 'Available on Windows only.',
      );
    }

    final nmBase = _browserNmBases[browserId];
    if (nmBase == null) {
      return NativeHostDiagnostics(
        browserId: browserId,
        registryKeyPresent: false,
        manifestFilePresent: false,
        manifestNameCorrect: false,
        manifestTypeCorrect: false,
        hostExecPresent: false,
        allowedOrigins: const [],
        parseError: 'Unknown browser: $browserId',
      );
    }

    final mPath = await _readRegistryDefault(
      'HKCU',
      '$nmBase\\$kNativeHostName',
    );

    if (mPath == null) {
      return NativeHostDiagnostics(
        browserId: browserId,
        registryKeyPresent: false,
        manifestFilePresent: false,
        manifestNameCorrect: false,
        manifestTypeCorrect: false,
        hostExecPresent: false,
        allowedOrigins: const [],
      );
    }

    final mFile = File(mPath);
    if (!mFile.existsSync()) {
      return NativeHostDiagnostics(
        browserId: browserId,
        registryKeyPresent: true,
        registryManifestPath: mPath,
        manifestFilePresent: false,
        manifestNameCorrect: false,
        manifestTypeCorrect: false,
        hostExecPresent: false,
        allowedOrigins: const [],
      );
    }

    Map<String, dynamic> manifest;
    try {
      manifest = jsonDecode(mFile.readAsStringSync()) as Map<String, dynamic>;
    } catch (e) {
      return NativeHostDiagnostics(
        browserId: browserId,
        registryKeyPresent: true,
        registryManifestPath: mPath,
        manifestFilePresent: true,
        manifestNameCorrect: false,
        manifestTypeCorrect: false,
        hostExecPresent: false,
        allowedOrigins: const [],
        parseError: 'JSON parse error: $e',
      );
    }

    final name = manifest['name'] as String?;
    final type = manifest['type'] as String?;
    final execPath = manifest['path'] as String?;
    final origins = (manifest['allowed_origins'] as List<dynamic>?)
            ?.map((e) => e.toString())
            .toList() ??
        const [];

    return NativeHostDiagnostics(
      browserId: browserId,
      registryKeyPresent: true,
      registryManifestPath: mPath,
      manifestFilePresent: true,
      manifestNameCorrect: name == kNativeHostName,
      manifestTypeCorrect: type == 'stdio',
      manifestHostExecPath: execPath,
      hostExecPresent: execPath != null && File(execPath).existsSync(),
      allowedOrigins: origins,
    );
  }

  // ── Registration ─────────────────────────────────────────────────────────────

  /// Validates the format of a Chrome extension ID (32 lowercase a–z letters).
  static String? validateExtensionId(String id) {
    if (id.length != 32) {
      return 'Must be exactly 32 characters (got ${id.length}).';
    }
    if (!_kExtensionIdRe.hasMatch(id)) {
      return 'Must contain only lowercase letters a–z.';
    }
    return null;
  }

  /// Writes the NM manifest and creates HKCU registry key for [browserId].
  ///
  /// Returns success=false with an error string on any failure.
  /// On success, also runs [diagnose] and returns it in [diagnostics].
  Future<RegistrationResult> registerHost({
    required String browserId,
    required String extensionId,
  }) async {
    if (!Platform.isWindows) {
      return const RegistrationResult(
        success: false,
        error: 'Native host registration is only supported on Windows.',
      );
    }

    final idError = validateExtensionId(extensionId);
    if (idError != null) {
      return RegistrationResult(success: false, error: idError);
    }

    final nmBase = _browserNmBases[browserId];
    if (nmBase == null) {
      return RegistrationResult(
        success: false,
        error: 'Unknown browser: $browserId',
      );
    }

    final hostExec = findHostExecutable();
    if (hostExec == null) {
      return const RegistrationResult(
        success: false,
        error:
            'Native host executable not found. '
            'Please reinstall CreatorForge to restore the host files.',
      );
    }

    // Ensure directory exists.
    try {
      await Directory(nativeHostDir).create(recursive: true);
    } catch (e) {
      return RegistrationResult(
        success: false,
        error: 'Could not create NativeHost directory: $e',
      );
    }

    // Write manifest.
    final origin = 'chrome-extension://$extensionId/';
    final manifest = {
      'name': kNativeHostName,
      'description': 'CreatorForge Native Messaging Host',
      'path': hostExec,
      'type': 'stdio',
      'allowed_origins': [origin],
    };

    try {
      File(manifestPath).writeAsStringSync(
        const JsonEncoder.withIndent('  ').convert(manifest),
      );
    } catch (e) {
      return RegistrationResult(
        success: false,
        error: 'Failed to write manifest: $e',
      );
    }

    // Register with the browser's native-messaging registry path.
    // /ve  — sets the unnamed default value (what Chrome reads)
    // /t   — REG_SZ string
    // /d   — the manifest path
    // /f   — overwrite without prompting
    final regKey = 'HKCU\\$nmBase\\$kNativeHostName';
    final regResult = await _runReg([
      'add',
      regKey,
      '/ve',
      '/t',
      'REG_SZ',
      '/d',
      manifestPath,
      '/f',
    ]);
    if (!regResult.success) {
      return RegistrationResult(success: false, error: regResult.error);
    }

    _log.info(
      'Registered $kNativeHostName for $browserId '
      '(extension=$extensionId, exec=$hostExec)',
    );

    final diag = await diagnose(browserId);
    if (!diag.isHealthy) {
      return RegistrationResult(
        success: false,
        error:
            'Registration written but post-check failed. '
            '${diag.parseError ?? "Run diagnostics for details."}',
        diagnostics: diag,
      );
    }
    return RegistrationResult(success: true, diagnostics: diag);
  }

  /// Removes the HKCU registry key for [browserId] (does not delete the
  /// manifest file — user data is preserved).
  Future<bool> unregisterHost(String browserId) async {
    if (!Platform.isWindows) return false;
    final nmBase = _browserNmBases[browserId];
    if (nmBase == null) return false;
    final regKey = 'HKCU\\$nmBase\\$kNativeHostName';
    final result = await _runReg(['delete', regKey, '/f']);
    return result.success;
  }

  // ── Browser actions ──────────────────────────────────────────────────────────

  /// Launches [browser] to its extensions management page.
  Future<bool> openExtensionsPage(BrowserInfo browser) async {
    final exec = browser.execPath;
    if (exec == null) return false;
    try {
      await Process.start(
        exec,
        ['chrome://extensions/'],
        mode: ProcessStartMode.detached,
      );
      return true;
    } catch (e) {
      _log.warning('Could not open extensions page: $e');
      return false;
    }
  }

  /// Opens [folderPath] in Windows Explorer.
  Future<bool> revealFolder(String folderPath) async {
    if (!Platform.isWindows) return false;
    try {
      await Process.start(
        'explorer.exe',
        [folderPath],
        mode: ProcessStartMode.detached,
      );
      return true;
    } catch (e) {
      _log.warning('Could not open explorer: $e');
      return false;
    }
  }

  // ── Private helpers ──────────────────────────────────────────────────────────

  /// Reads the default (unnamed) value of a Windows registry key via `reg query`.
  Future<String?> _readRegistryDefault(String hive, String subKey) async {
    try {
      final result = await Process.run(
        'reg',
        ['query', '$hive\\$subKey', '/ve'],
        runInShell: false,
      );
      if (result.exitCode != 0) return null;
      final stdout = (result.stdout as String).trim();
      // Output line format:  "    (Default)    REG_SZ    <value>"
      final match =
          RegExp(r'\(Default\)\s+REG_\w+\s+(.+)$', multiLine: true).firstMatch(
            stdout,
          );
      return match?.group(1)?.trim();
    } catch (e) {
      _log.fine('Registry read failed ($hive\\$subKey): $e');
      return null;
    }
  }

  Future<({bool success, String? error})> _runReg(List<String> args) async {
    try {
      final result = await Process.run(
        'reg',
        args,
        runInShell: false,
      );
      if (result.exitCode != 0) {
        return (
          success: false,
          error: 'reg ${args.first} failed (exit ${result.exitCode}): '
              '${(result.stderr as String).trim()}',
        );
      }
      return (success: true, error: null);
    } catch (e) {
      return (success: false, error: 'Failed to run reg.exe: $e');
    }
  }
}
